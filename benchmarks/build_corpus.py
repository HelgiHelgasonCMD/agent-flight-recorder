"""Build the synthetic retrieval benchmark corpus deterministically.

Outputs (committed, regenerated by running this file):
  benchmarks/corpus/history.jsonl  afr.generic-event.v1 records: past episodes, verifications, lessons
  benchmarks/corpus/queries.json   new-task queries with graded relevance judgments and trap labels

The episodes are synthetic but technically plausible. Relevance judgments are by
episode id: grade 2 = the applicable, verified fix for this query's situation;
grade 1 = related and useful (e.g. a stale but still-correct fix, or a failed attempt
worth knowing about). ``traps`` are episodes that look relevant but must be flagged with
one of the listed caution codes (inapplicable precondition, version mismatch, failed
attempt, unverified claim). Each query has an ``as_of`` time; anything recorded later
is a future record and must never be retrieved (leakage guard).
"""

from __future__ import annotations

import json
from datetime import UTC, datetime, timedelta
from pathlib import Path
from typing import Any

OUT = Path(__file__).parent / "corpus"
BASE = datetime(2026, 1, 5, 9, 0, tzinfo=UTC)
REPO_A = "repo_bench_api"
REPO_B = "repo_bench_web"
REPO_C = "repo_bench_tools"

records: list[dict[str, Any]] = []
episode_meta: dict[str, dict[str, Any]] = {}


def iso(dt: datetime) -> str:
    return dt.isoformat()


def ep(
    eid: str,
    family: str,
    day: float,
    task: str,
    command: str,
    error: str,
    fix: str | None,
    *,
    repo: str = REPO_A,
    language: str = "python",
    failed: list[str] | None = None,
    outcome: str = "verified",  # verified | failed_check | claimed | none
    check: str | None = None,
    versions: dict[str, str] | None = None,
    lesson: dict[str, Any] | None = None,
    edit_files: list[str] | None = None,
) -> None:
    t = BASE + timedelta(days=day)
    common = {
        "schema": "afr.generic-event.v1",
        "session_id": f"sess-{eid}",
        "episode_id": eid,
        "agent": "bench-agent",
        "repo": repo,
        "language": language,
        "task_family": family,
        "versions": versions or {},
    }
    n = 0

    def add(kind: str, **kw: Any) -> None:
        nonlocal n
        n += 1
        rec = {**common, "event_id": f"{eid}-{n:02d}", "ts": iso(t + timedelta(minutes=n)), "kind": kind}
        rec.update(kw)
        records.append(rec)

    add("prompt", task_summary=task)
    add("tool_failure", tool={"name": "Bash", "command": command, "exit_code": 1}, error=error)
    for attempt in failed or []:
        add("tool_result", tool={"name": "Bash", "command": attempt, "exit_code": 0})
        add("tool_failure", tool={"name": "Bash", "command": command, "exit_code": 1}, error=error)
    if fix:
        if edit_files:
            add("tool_result", tool={"name": "Edit", "files": edit_files})
        add("tool_result", tool={"name": "Bash", "command": fix, "exit_code": 0})
    if outcome == "verified":
        add(
            "verification",
            verification={"kind": "test_command", "command": check or command, "exit_code": 0, "passed": True},
        )
    elif outcome == "failed_check":
        add(
            "verification",
            verification={"kind": "test_command", "command": check or command, "exit_code": 1, "passed": False},
        )
    elif outcome == "claimed":
        add("stop", assistant_claim="Fixed it — should work now.")
    if lesson is not None:
        add("lesson", lesson=lesson)
    episode_meta[eid] = {"family": family, "ts": iso(t), "repo": repo}


